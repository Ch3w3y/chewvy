def inline(text):
    """The few inline forms this file uses: links, code, emphasis."""
    text = html.escape(text, quote=False).replace("\\|", "|")
    # A URL may hold one level of brackets, as Commons file names do.
    text = re.sub(r"\[([^\]]+)\]\(((?:[^()\s]|\([^()\s]*\))+)\)", r'<a href="\2">\1</a>', text)
    text = re.sub(r"`([^`]+)`", r"<code>\1</code>", text)
    return re.sub(r"\*([^*]+)\*", r"<em>\1</em>", text)


def html_page(lines):
    """credits.html: the same content as CREDITS.md, as a page of the site."""
    body, paragraph, rows = [], [], []

    def flush():
        if paragraph:
            body.append("<p>" + inline(" ".join(paragraph)) + "</p>")
            paragraph.clear()
        if rows:
            head, *rest = rows
            cells = lambda row, tag: "".join(f"<{tag}>{inline(c.strip())}</{tag}>" for c in re.split(r"(?<!\\)\|", row.strip().strip("|")))
            body.append('<div class="table-wrap" tabindex="0" role="region" aria-label="Credits table"><table><thead><tr>'
                        + cells(head, "th") + "</tr></thead><tbody>"
                        + "".join(f"<tr>{cells(row, 'td')}</tr>" for row in rest) + "</tbody></table></div>")
            rows.clear()

    for line in lines:
        if line.startswith("|"):
            if not re.match(r"^\|[-|]+\|$", line):
                rows.append(line)
        elif line.startswith("#"):
            flush()
            level = len(line) - len(line.lstrip("#"))
            body.append(f"<h{level}>{inline(line.lstrip('# '))}</h{level}>")
        elif line.strip():
            if rows:
                flush()
            paragraph.append(line)
        else:
            flush()
    flush()
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Credits: Chewvy</title>
<meta name="description" content="Authors, licences and sources of every photograph, film and image on the Chewvy website.">
<meta name="color-scheme" content="dark">
<link rel="icon" href="assets/brand/icon.svg" type="image/svg+xml">
<link rel="stylesheet" href="styles.css">
</head>
<body class="plain">
<a class="skip" href="#main">Skip to content</a>
<div class="backdrop" aria-hidden="true"><div class="backdrop-layer is-on" style="background-image:url('assets/themes/aurora.webp')"></div></div>
<header class="top">
  <a class="brand" href="index.html" aria-label="Chewvy, home"><img src="assets/brand/lockup.svg" width="137" height="32" alt="Chewvy"></a>
  <a class="btn btn-ghost top-gh" href="index.html">Back to the site</a>
</header>
<main id="main" class="prose glass">
{chr(10).join(body)}
</main>
</body>
</html>
"""


if __name__ == "__main__":
    main()
