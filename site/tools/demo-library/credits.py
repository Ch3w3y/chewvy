"""Write site/CREDITS.md from what was really downloaded and bundled.

Sources: library.json (the titles), the provenance records build.py wrote
beside the library (where each file came from, its licence and its hash), and
site/assets/themes/themes.json (the background photographs, from the app's
own SOURCES.md). Run through `build.py credits`.
"""
